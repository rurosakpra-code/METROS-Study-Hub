create or replace view public.overall_leaderboard with (security_invoker=false) as
select p.id as user_id,coalesce(nullif(trim(p.display_name),''),'Student') as display_name,
 count(a.id)::integer as quiz_count,round(avg(a.score/a.total_marks*100),2) as average_percentage
from public.profiles p join public.quiz_attempts a on a.user_id=p.id
where p.leaderboard_opt_in=true and a.is_verified=true
  and exists(select 1 from public.feature_settings where key='leaderboards' and enabled=true)
group by p.id,p.display_name having count(a.id)>=3;

create or replace view public.course_leaderboard with (security_invoker=false) as
select p.id as user_id,coalesce(nullif(trim(p.display_name),''),'Student') as display_name,a.course,
 count(a.id)::integer as quiz_count,round(avg(a.score/a.total_marks*100),2) as average_percentage
from public.profiles p join public.quiz_attempts a on a.user_id=p.id
where p.leaderboard_opt_in=true and a.is_verified=true
  and exists(select 1 from public.feature_settings where key='leaderboards' and enabled=true)
group by p.id,p.display_name,a.course having count(a.id)>=3;

create or replace view public.weekly_leaderboard with (security_invoker=false) as
select p.id as user_id,coalesce(nullif(trim(p.display_name),''),'Student') as display_name,
 count(a.id)::integer as quiz_count,round(avg(a.score/a.total_marks*100),2) as average_percentage
from public.profiles p join public.quiz_attempts a on a.user_id=p.id
where p.leaderboard_opt_in=true and a.is_verified=true and a.created_at>=now()-interval '7 days'
  and exists(select 1 from public.feature_settings where key='leaderboards' and enabled=true)
group by p.id,p.display_name having count(a.id)>=3;

create or replace view public.most_improved_leaderboard with (security_invoker=false) as
with periods as (
 select a.user_id,
 count(*) filter(where a.created_at>=now()-interval '7 days') as current_count,
 count(*) filter(where a.created_at>=now()-interval '14 days' and a.created_at<now()-interval '7 days') as previous_count,
 avg(a.score/a.total_marks*100) filter(where a.created_at>=now()-interval '7 days') as current_average,
 avg(a.score/a.total_marks*100) filter(where a.created_at>=now()-interval '14 days' and a.created_at<now()-interval '7 days') as previous_average
 from public.quiz_attempts a where a.is_verified=true and a.created_at>=now()-interval '14 days' group by a.user_id
)
select x.user_id,coalesce(nullif(trim(p.display_name),''),'Student') as display_name,
 x.previous_count::integer as previous_quiz_count,x.current_count::integer as current_quiz_count,
 round(x.previous_average,2) as previous_average,round(x.current_average,2) as current_average,
 round(x.current_average-x.previous_average,2) as improvement_percentage_points
from periods x join public.profiles p on p.id=x.user_id
where p.leaderboard_opt_in=true and x.current_count>=3 and x.previous_count>=3
  and exists(select 1 from public.feature_settings where key='leaderboards' and enabled=true);

create or replace view public.recent_group_activity with (security_invoker=false) as

-- Admin-only RPC for aggregate site summary. RLS also checks admin membership.
create or replace function public.get_admin_summary()
returns jsonb language plpgsql security definer set search_path=public
as $$
begin
 if not public.is_current_user_admin() then raise exception 'Administrator access required'; end if;
 return jsonb_build_object(
  'student_count',(select count(*) from public.profiles),
  'quiz_count',(select count(*) from public.quizzes),

create or replace function public.prepare_group_chat_message()
returns trigger language plpgsql security definer set search_path=public
as $$
begin
  select coalesce(nullif(trim(p.display_name),''),'Student') into new.display_name
  from public.profiles p where p.id=new.user_id;
  if new.display_name is null then new.display_name='Student'; end if;
  new.created_at=now();
  new.expires_at=now()+interval '7 days';
  return new;
end; $$;
drop trigger if exists prepare_group_chat_message_before_insert on public.group_chat_messages;
create trigger prepare_group_chat_message_before_insert
before insert on public.group_chat_messages for each row
execute function public.prepare_group_chat_message();


create or replace function public.record_user_active_time(p_active_seconds integer,p_page text default null)
returns void language plpgsql security definer set search_path=public
as $$
declare
  current_user_id uuid:=auth.uid();
begin
  if current_user_id is null then raise exception 'Sign-in required'; end if;
  if p_active_seconds is null or p_active_seconds<1 or p_active_seconds>60 then
    raise exception 'Active time increment must be between 1 and 60 seconds';
  end if;
  if p_page is not null and p_page not in ('home','classes','quizzes','progress','resources','profile','admin') then
    raise exception 'Invalid page';
  end if;
  insert into public.user_activity_daily(user_id,activity_date,active_seconds,last_active_at,last_page)
  values(current_user_id,(now() at time zone 'utc')::date,p_active_seconds,now(),p_page)
  on conflict(user_id,activity_date) do update set
    active_seconds=least(86400,public.user_activity_daily.active_seconds+excluded.active_seconds),
    last_active_at=excluded.last_active_at,last_page=excluded.last_page;
end; $$;
revoke all on function public.record_user_active_time(integer,text) from public;
grant execute on function public.record_user_active_time(integer,text) to authenticated;

create or replace function public.get_admin_user_last_activity(p_user_ids uuid[])
returns table(user_id uuid,last_activity_at timestamptz)
language plpgsql security definer set search_path=public
as $$
begin
  if not public.is_current_user_admin() then raise exception 'Administrator access required'; end if;
  if coalesce(cardinality(p_user_ids),0)>100 then raise exception 'A maximum of 100 users can be queried at once'; end if;
  return query
    select activity.user_id,max(activity.occurred_at)
    from (
      select log.user_id,log.created_at as occurred_at from public.user_activity_log log
      where log.user_id=any(coalesce(p_user_ids,array[]::uuid[]))
      union all
      select daily.user_id,daily.last_active_at as occurred_at from public.user_activity_daily daily
      where daily.user_id=any(coalesce(p_user_ids,array[]::uuid[]))
    ) activity
    group by activity.user_id;
end; $$;
revoke all on function public.get_admin_user_last_activity(uuid[]) from public;
grant execute on function public.get_admin_user_last_activity(uuid[]) to authenticated;

